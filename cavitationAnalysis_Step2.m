%% TOTAL CAV DOSE, all days
% Combining results across days for "total cav dose"
% ——— Variables & Setup ———
nVar    = numel(vars);
nAnimals = numel(results_2);

% Build variable names and types for the summary table
colNames   = ["PressureAnimal"];
colTypes   = ["string"];
for iV = 1:nVar
  v = vars{iV};
  colNames(end+1:end+2) = [v+"_TotalAUC", v+"_TotalAUC_SD"];
  colTypes(end+1:end+2) = ["double","double"];
end

% Preallocate table
T_summary = table('Size',[nAnimals,1+2*nVar], ...
                  'VariableTypes',colTypes, ...
                  'VariableNames',colNames);

% ——— Fill in each row ———
for i = 1:nAnimals
  % assume same animalnum & pressure in each results_N
  an   = results_2(i).animalnum;
  pres = results_2(i).pressure;
  
  % 1) PressureAnimal string
  T_summary.PressureAnimal(i) = sprintf("%d_%d", pres, an);
  
  % 2) Loop variables
  for j = 1:nVar
    v = vars{j};
    
    % pull the three days
    A1 = results_2(i).(v).totalAUC;
    A2 = results_3(i).(v).totalAUC;
    A3 = results_4(i).(v).totalAUC;
    
    S1 = results_2(i).(v).totalAUC_SD;
    S2 = results_3(i).(v).totalAUC_SD;
    S3 = results_4(i).(v).totalAUC_SD;
    
    % sum of AUCs
    sumAUC  = sum([A1, A2, A3],'omitnan');
    % propagate SD: sqrt(Σ sd_i^2)
    sumVar  = S1.^2 + S2.^2 + S3.^2;
    sumSD   = sqrt(sumVar);
    
    % assign into table
    T_summary{i, v+"_TotalAUC"}    = sumAUC;
    T_summary{i, v+"_TotalAUC_SD"} = sumSD;
  end
end

T_summary = sortrows(T_summary, 'PressureAnimal', 'ascend');
